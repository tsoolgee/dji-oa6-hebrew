# משלים עברית לכל האפשרויות שהיו רק באנגלית, והסברים לפריטים בלי הסבר
import pathlib, re
p = pathlib.Path(__file__).parent.parent / 'src/data.js'
s = p.read_text(encoding='utf-8')

def rep(a, b):
    global s
    assert a in s, 'MISSING ' + a[:70]
    s = s.replace(a, b, 1)

def secs(v):
    n = v[:-1]
    return 'חצי שנייה' if n == '0.5' else 'שנייה' if n == '1' else f'{n} שניות'

# פרק זמן בשניות: '5s' -> ['5s', '5 שניות']
for id_ in ['p_prerec', 'p_countdown', 'p_interval']:
    m = re.search(r"node\('" + id_ + r"', \{.*?\}\);\n", s, re.S)
    block = m.group(0)
    nb = re.sub(r"(?<=[(,] )'(\d+(?:\.\d+)?s)'", lambda x: f"['{x.group(1)}', '{secs(x.group(1))}']", block)
    s = s.replace(block, nb)

RES = {'8K': '8K ‏(7680×4320, הכי חד)', '4K': '4K ‏(3840×2160)', '2.7K': '2.7K ‏(2688×1512)', '1080p': '1080p ‏(Full HD)'}
