    m = re.search(r"node\('" + id_ + r"', \{.*?\}\);\n", s, re.S)
    block = m.group(0)
    nb = re.sub(r"o: O\(([^)]*)\)", lambda x: 'o: O(' + ', '.join(f"['{v}', '{RES[v]}']" for v in re.findall(r"'([^']+)'", x.group(1))) + ')', block, count=1)
    s = s.replace(block, nb)

